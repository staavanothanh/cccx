use std::collections::BTreeMap;
use std::path::Path;
use thiserror::Error;

const ROUTES_FILE: &str = "cccx-agent-model-routes.json";

#[derive(Debug, Error)]
pub enum AgentModelRouteStoreError {
    #[error("invalid agent preset `{0}`")]
    InvalidPreset(String),
    #[error("invalid model route `{0}`")]
    InvalidRoute(String),
    #[error("failed to read CCCX agent model routes: {0}")]
    Read(#[from] std::io::Error),
    #[error("failed to parse CCCX agent model routes: {0}")]
    Parse(#[from] serde_json::Error),
    #[error("failed to resolve configured 9router model route: {0}")]
    Resolve(#[from] ProviderGatewayError),
    #[error("conflicting agent model suggestions `{work_spec_route}` and `{tool_route}`")]
    ConflictingAgentSuggestion {
        work_spec_route: String,
        tool_route: String,
    },
}

/// The immutable model-route decision made by Main CC at the spawn boundary.
/// A raw spawn tool call is generated by the agent, so it is intentionally not
/// treated as a user override.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedSpawnModelRoute {
    pub route_id: String,
    pub selection_source: String,
    pub fallback_policy_id: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
struct AgentModelRoutes {
    #[serde(default)]
    routes: BTreeMap<String, String>,
}

pub async fn set_agent_model_route(
    codex_home: &Path,
    preset: &str,
    route: &str,
) -> Result<(), AgentModelRouteStoreError> {
    validate_key(preset).map_err(|_| AgentModelRouteStoreError::InvalidPreset(preset.into()))?;
    validate_key(route).map_err(|_| AgentModelRouteStoreError::InvalidRoute(route.into()))?;
    let path = codex_home.join(ROUTES_FILE);
    let mut routes = read_routes_file(&path).await?;
    routes
        .routes
        .insert(normalize_preset(preset), route.to_string());
    tokio::fs::create_dir_all(codex_home).await?;
    let data = serde_json::to_vec_pretty(&routes)?;
    tokio::fs::write(path, data).await?;
    Ok(())
}

pub async fn route_for_work_role(
    codex_home: &Path,
    role: &WorkRole,
) -> Result<Option<ModelRouteSelection>, AgentModelRouteStoreError> {
    let path = codex_home.join(ROUTES_FILE);
    if tokio::fs::metadata(&path).await.is_err() {
        return Ok(None);
    }
    let routes = read_routes_file(&path).await?;
    let role_key = normalize_work_role(role);
    Ok(routes
        .routes
        .get(&role_key)
        .cloned()
        .map(|route_id| ModelRouteSelection::Explicit { route_id }))
}

/// Resolve the model route at the Main CC scheduler boundary. Explicit routes
/// inside a WorkSpec and the upstream `spawn_agent.model` field are both
/// agent-suggested input; only a future trusted UI/API field may populate the
/// resolver's `user_override_route_id`.
pub fn resolve_spawn_model_route(
    catalog: &LocalConfigCatalog,
    main_requested_route_id: &str,
    requested: &ModelRouteSelection,
    role_preset: Option<ModelRouteSelection>,
) -> Result<ResolvedSpawnModelRoute, AgentModelRouteStoreError> {
    resolve_spawn_model_route_with_agent_suggestion(
        catalog,
        main_requested_route_id,
        requested,
        role_preset,
        None,
    )
}

pub fn resolve_spawn_model_route_with_agent_suggestion(
    catalog: &LocalConfigCatalog,
    main_requested_route_id: &str,
    requested: &ModelRouteSelection,
    role_preset: Option<ModelRouteSelection>,
    tool_model_suggestion: Option<&str>,
) -> Result<ResolvedSpawnModelRoute, AgentModelRouteStoreError> {
    resolve_spawn_model_route_with_agent_suggestion_and_main_effective(
        catalog,
        main_requested_route_id,
        None,
        requested,
        role_preset,
        tool_model_suggestion,
    )
}

/// Resolves at the Main CC scheduler boundary with only factual effective
/// route metadata observed from an earlier 9router request. Callers must pass
/// `None` when the gateway did not report one; deriving it from a requested
/// opaque route is forbidden.
pub fn resolve_spawn_model_route_with_agent_suggestion_and_main_effective(
    catalog: &LocalConfigCatalog,
    main_requested_route_id: &str,
    main_effective_route_id: Option<&str>,
    requested: &ModelRouteSelection,
    role_preset: Option<ModelRouteSelection>,
    tool_model_suggestion: Option<&str>,
) -> Result<ResolvedSpawnModelRoute, AgentModelRouteStoreError> {
    let work_spec_suggestion = explicit_route_id(requested).map(str::to_string);
    let tool_model_suggestion = tool_model_suggestion
        .map(str::trim)
        .filter(|route| !route.is_empty())
        .map(str::to_string);
    if let (Some(work_spec_route), Some(tool_route)) =
        (&work_spec_suggestion, &tool_model_suggestion)
        && work_spec_route != tool_route
    {
        return Err(AgentModelRouteStoreError::ConflictingAgentSuggestion {
            work_spec_route: work_spec_route.clone(),
            tool_route: tool_route.clone(),
        });
    }
    let agent_suggested_route_id = tool_model_suggestion.or(work_spec_suggestion);
    let session_default_subagent_model = catalog
        .default_subagent_model
        .as_ref()
        .cloned()
        .map(SubagentModelRouteRequest::RouteId)
        .or_else(|| match requested {
            ModelRouteSelection::InheritMainEffective => {
                Some(SubagentModelRouteRequest::InheritMainEffective)
            }
            ModelRouteSelection::InheritMainRequested | ModelRouteSelection::Explicit { .. } => {
                None
            }
        });
    let catalog = model_route_catalog(catalog);
    let resolved =
        ModelRouteResolver::new(&catalog).resolve_subagent_route(ModelRouteResolveRequest {
            user_override_route_id: None,
            role_preset_route_id: role_preset
                .as_ref()
                .and_then(|selection| explicit_route_id(selection).map(str::to_string)),
            agent_suggested_route_id,
            session_default_subagent_model,
            main_requested_route_id: Some(main_requested_route_id.to_string()),
            main_effective_route_id: main_effective_route_id.map(str::to_string),
        })?;
    Ok(ResolvedSpawnModelRoute {
        route_id: resolved.route.route_id,
        selection_source: selection_source_label(resolved.provenance.selection_source).to_string(),
        fallback_policy_id: fallback_policy_label(resolved.route.fallback_policy_id).to_string(),
    })
}

fn model_route_catalog(local: &LocalConfigCatalog) -> ModelRouteCatalog {
    ModelRouteCatalog::new(
        local
            .available_models
            .iter()
            .cloned()
            .map(|route_id| ModelRoute {
                model_id: route_id.clone(),
                route_id,
                // Local owner catalogs currently contain opaque IDs only. Do not claim
                // provider-derived capabilities until a richer catalog schema exists.
                model_profile_id: "configured-opaque-route".to_string(),
                capability_profile_id: "configured-unknown".to_string(),
                fallback_policy_id: local.fallback_policy_id,
            }),
    )
    .with_global_default_route_id(local.default_model.clone())
}

fn explicit_route_id(selection: &ModelRouteSelection) -> Option<&str> {
    match selection {
        ModelRouteSelection::Explicit { route_id } => Some(route_id),
        ModelRouteSelection::InheritMainRequested | ModelRouteSelection::InheritMainEffective => {
            None
        }
    }
}

fn selection_source_label(source: ModelRouteSelectionSource) -> &'static str {
    match source {
        ModelRouteSelectionSource::UserOverride => "user_override",
        ModelRouteSelectionSource::RolePreset => "role_preset",
        ModelRouteSelectionSource::AgentSuggested => "agent_suggested",
        ModelRouteSelectionSource::SessionDefault => "session_default",
        ModelRouteSelectionSource::InheritMainRequested => "inherit_main_requested",
        ModelRouteSelectionSource::InheritMainEffective => "inherit_main_effective",
        ModelRouteSelectionSource::GlobalDefault => "global_default",
    }
}

fn fallback_policy_label(policy: FallbackPolicyId) -> &'static str {
    match policy {
        FallbackPolicyId::Strict => "strict",
        FallbackPolicyId::Compatible => "compatible",
        FallbackPolicyId::RouterDefault => "router_default",
    }
}

fn validate_key(value: &str) -> Result<(), ()> {
    let trimmed = value.trim();
    if trimmed.is_empty() || trimmed.chars().any(char::is_control) {
        return Err(());
    }
    Ok(())
}

fn normalize_work_role(role: &WorkRole) -> String {
    format!("{role:?}").to_ascii_lowercase()
}

fn normalize_preset(preset: &str) -> String {
    preset
        .trim()
        .trim_start_matches("cc:")
        .trim_start_matches("cx:")
        .trim_start_matches("cc_")
        .trim_start_matches("cx_")
        .to_ascii_lowercase()
}

async fn read_routes_file(path: &Path) -> Result<AgentModelRoutes, AgentModelRouteStoreError> {
    match tokio::fs::read(path).await {
        Ok(bytes) => Ok(serde_json::from_slice(&bytes)?),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            Ok(AgentModelRoutes::default())
        }
        Err(error) => Err(AgentModelRouteStoreError::Read(error)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[tokio::test]
    async fn route_for_work_role_reads_normalized_preset() {
        let home = tempdir().unwrap();
        set_agent_model_route(home.path(), "cx_implementer", "oc/deepseek-v4")
            .await
            .unwrap();

        assert_eq!(
            route_for_work_role(home.path(), &WorkRole::Implementer)
                .await
                .unwrap(),
            Some(ModelRouteSelection::Explicit {
                route_id: "oc/deepseek-v4".to_string()
            })
        );
    }

    #[tokio::test]
    async fn route_store_rejects_empty_or_control_values() {
        let home = tempdir().unwrap();
        assert!(
            set_agent_model_route(home.path(), "", "oc/model")
                .await
                .is_err()
        );
        assert!(
            set_agent_model_route(home.path(), "implementer", "oc/\nmodel")
                .await
                .is_err()
        );
    }

    fn catalog() -> LocalConfigCatalog {
        LocalConfigCatalog {
            default_model: "9router/main".to_string(),
            available_models: vec![
                "9router/main".to_string(),
                "9router/role".to_string(),
                "9router/suggested".to_string(),
            ],
            default_subagent_model: None,
            fallback_policy_id: FallbackPolicyId::Strict,
            fetched_at: None,
            source: None,
            digest: None,
        }
    }

    #[test]
    fn role_preset_wins_over_agent_suggested_work_spec_route() {
        let resolved = resolve_spawn_model_route(
            &catalog(),
            "9router/main",
            &ModelRouteSelection::Explicit {
                route_id: "9router/suggested".to_string(),
            },
            Some(ModelRouteSelection::Explicit {
                route_id: "9router/role".to_string(),
            }),
        )
        .unwrap();

        assert_eq!(resolved.route_id, "9router/role");
        assert_eq!(resolved.selection_source, "role_preset");
    }

    #[test]
    fn explicit_work_spec_route_is_agent_suggested_not_user_override() {
        let resolved = resolve_spawn_model_route(
            &catalog(),
            "9router/main",
            &ModelRouteSelection::Explicit {
                route_id: "9router/suggested".to_string(),
            },
            None,
        )
        .unwrap();

        assert_eq!(resolved.route_id, "9router/suggested");
        assert_eq!(resolved.selection_source, "agent_suggested");
    }

    #[test]
    fn inherited_requested_route_is_the_default_without_preset_or_suggestion() {
        let resolved = resolve_spawn_model_route(
            &catalog(),
            "9router/main",
            &ModelRouteSelection::InheritMainRequested,
            None,
        )
        .unwrap();

        assert_eq!(resolved.route_id, "9router/main");
        assert_eq!(resolved.selection_source, "inherit_main_requested");
    }

    #[test]
    fn conflicting_work_spec_and_tool_suggestions_fail_closed() {
        let error = resolve_spawn_model_route_with_agent_suggestion(
            &catalog(),
            "9router/main",
            &ModelRouteSelection::Explicit {
                route_id: "9router/suggested".to_string(),
            },
            None,
            Some("9router/main"),
        )
        .unwrap_err();

        assert!(matches!(
            error,
            AgentModelRouteStoreError::ConflictingAgentSuggestion { .. }
        ));
    }

    #[test]
    fn inherited_effective_route_uses_only_factual_gateway_metadata() {
        let resolved = resolve_spawn_model_route_with_agent_suggestion_and_main_effective(
            &catalog(),
            "9router/main",
            Some("9router/role"),
            &ModelRouteSelection::InheritMainEffective,
            None,
            None,
        )
        .unwrap();

        assert_eq!(resolved.route_id, "9router/role");
        assert_eq!(resolved.selection_source, "inherit_main_effective");
    }

    #[test]
    fn owner_default_subagent_model_precedes_inherit_main_requested() {
        let mut catalog = catalog();
        catalog.default_subagent_model = Some("9router/role".to_string());

        let resolved = resolve_spawn_model_route(
            &catalog,
            "9router/main",
            &ModelRouteSelection::InheritMainRequested,
            None,
        )
        .unwrap();

        assert_eq!(resolved.route_id, "9router/role");
        assert_eq!(resolved.selection_source, "session_default");
    }
}
